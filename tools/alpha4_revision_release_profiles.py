def write_python(target: Path, record: dict[str, object], identity_digest: str) -> None:
    text = f'''"""Generated ASET Revision 0.4alpha Revision Python companion.

External release companion. Semantic precedence: none.
"""

from __future__ import annotations

from typing import Iterable

SUBJECT_ID = "ASET-REVISION-0.4-ALPHA"
VERSION = "0.4alpha"
SEMANTIC_PRECEDENCE = "NONE"
SOURCE_BYTE_IDENTITY_DIGEST = {identity_digest!r}
COMPONENT_ID = {str(record["component_id"])!r}
OPERATIONAL_WORD = {str(record["operational_word"])!r}
FORMAL_OPERATOR = {str(record["formal_operator"])!r}
SEED_PROJECTION = "OBSERVE-UNKNOWN"
TERMINAL_RECOGNITION_OWNED = False
EFFECT_PERMISSION_OWNED = False

Proposal = tuple[str, str, str, str]
State = tuple[Proposal, ...]


def proposal(
    target: str,
    genesis: str,
    from_state: str,
    to_state: str,
) -> Proposal:
    return (target, genesis, from_state, to_state)


def state(proposals: Iterable[Proposal] = ()) -> State:
    return tuple(sorted(set(proposals)))


def valid_proposal(candidate: Proposal) -> bool:
    if not isinstance(candidate, tuple) or len(candidate) != 4:
        return False
    target, genesis, from_state, to_state = candidate
    return (
        all(isinstance(item, str) for item in candidate)
        and target == genesis
        and from_state != to_state
    )


def propose_revision(current: State, candidate: Proposal) -> State:
    normalized = state(current)
    if any(not valid_proposal(item) for item in normalized):
        raise ValueError("invalid proposal state")
    if not valid_proposal(candidate):
        raise ValueError("invalid revision proposal")
    if candidate in normalized:
        raise ValueError("revision proposal is not fresh")
    return state((*normalized, candidate))
'''
    target.write_text(text, encoding="utf-8")


def write_python_sqlite(target: Path, base_expression_sha256: str) -> None:
    text = f'''"""Generated ASET Revision 0.4alpha Revision Python SQLite persistence extension.

Persistence extension of the exact generated Python companion.
Semantic delta: none. Semantic precedence: none.
"""

from __future__ import annotations

import hashlib
import importlib.util
import sqlite3
from pathlib import Path
from typing import Any

BASE_EXPRESSION_SHA256 = {base_expression_sha256!r}
BASE_EXPRESSION_PATH = (
    Path(__file__).resolve().parents[1] / "python" / "aset_revision_alpha4.py"
)
SEMANTIC_DELTA = "NONE"
SEMANTIC_PRECEDENCE = "NONE"


def _sha256(path: Path) -> str:
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def _load_base_expression() -> Any:
    if _sha256(BASE_EXPRESSION_PATH) != BASE_EXPRESSION_SHA256:
        raise RuntimeError("base Python expression byte identity mismatch")
    spec = importlib.util.spec_from_file_location(
        "aset_revision_alpha4_base_expression",
        BASE_EXPRESSION_PATH,
    )
    if spec is None or spec.loader is None:
        raise RuntimeError("base Python expression cannot be loaded")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_base_expression = _load_base_expression()


class SQLiteStore:
    def __init__(self, path: str | Path) -> None:
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self._connect() as connection:
            connection.execute(
                "CREATE TABLE IF NOT EXISTS proposals ("
                "target TEXT NOT NULL, "
                "genesis TEXT NOT NULL, "
                "from_state TEXT NOT NULL, "
                "to_state TEXT NOT NULL, "
                "PRIMARY KEY (target, genesis, from_state, to_state), "
                "CHECK (target = genesis), "
                "CHECK (from_state <> to_state)"
                ")"
            )

    def _connect(self) -> sqlite3.Connection:
        return sqlite3.connect(self.path)

    def load(self) -> tuple[tuple[str, str, str, str], ...]:
        with self._connect() as connection:
            rows = connection.execute(
                "SELECT target, genesis, from_state, to_state "
                "FROM proposals ORDER BY target, genesis, from_state, to_state"
            ).fetchall()
        return tuple(tuple(str(value) for value in row) for row in rows)

    def replace(self, current: tuple[tuple[str, str, str, str], ...]) -> None:
        normalized = _base_expression.state(current)
        if any(not _base_expression.valid_proposal(item) for item in normalized):
            raise ValueError("invalid persistent proposal state")
        with self._connect() as connection:
            connection.execute("BEGIN IMMEDIATE")
            connection.execute("DELETE FROM proposals")
            connection.executemany(
                "INSERT INTO proposals (target, genesis, from_state, to_state) "
                "VALUES (?, ?, ?, ?)",
                normalized,
            )

    def propose_revision(
        self,
        candidate: tuple[str, str, str, str],
    ) -> tuple[tuple[str, str, str, str], ...]:
        with self._connect() as connection:
            connection.execute("BEGIN IMMEDIATE")
            rows = connection.execute(
                "SELECT target, genesis, from_state, to_state "
                "FROM proposals ORDER BY target, genesis, from_state, to_state"
            ).fetchall()
            current = tuple(tuple(str(value) for value in row) for row in rows)
            result = _base_expression.propose_revision(current, candidate)
            connection.execute(
                "INSERT INTO proposals (target, genesis, from_state, to_state) "
                "VALUES (?, ?, ?, ?)",
                candidate,
            )
            return result
'''
    target.write_text(text, encoding="utf-8")


