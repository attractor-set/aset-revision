from __future__ import annotations

import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUBJECT = ROOT / "revision/alpha4/REVISION.aset"
FORTH = ROOT / "revision/alpha4/operational/components.forth"
REL = ROOT / "revision/alpha4/formal/RevisionRelations.tla"
SEED_PROJECTION = ROOT / "revision/alpha4/formal/SeedProjection.tla"
CAUSAL = ROOT / "revision/alpha4/causal/components.petri"


def sha256(path: Path) -> str:
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def source_digest(paths: tuple[Path, ...]) -> str:
    digest = hashlib.sha256()
    for path in sorted(paths, key=lambda item: item.relative_to(ROOT).as_posix()):
        relative = path.relative_to(ROOT).as_posix()
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return "sha256:" + digest.hexdigest()


def _subject_pair() -> tuple[str, str, str, str]:
    for raw in SUBJECT.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("PAIR "):
            tokens = line.split()
            if len(tokens) != 5:
                raise RuntimeError("invalid Revision PAIR declaration")
            return (tokens[1], tokens[2], tokens[3], tokens[4])
    raise RuntimeError("Revision PAIR declaration missing")


def companion_record() -> dict[str, object]:
    component_id, operational_word, formal_operator, proof = _subject_pair()
    forth = FORTH.read_text(encoding="utf-8")
    relational = REL.read_text(encoding="utf-8")
    projection = SEED_PROJECTION.read_text(encoding="utf-8")
    required_forth = (
        "VALID-PROPOSAL?",
        "FRESH-PROPOSAL?",
        "APPEND-PROPOSAL",
    )
    if not all(token in forth for token in required_forth):
        raise RuntimeError("Revision operational expression drift")
    required_relational = (
        "p.target = p.transition.genesis",
        "tr.fromState # tr.toState",
        "p \\notin s",
        "t = s \\cup {p}",
    )
    if not all(token in relational for token in required_relational):
        raise RuntimeError("Revision relational expression drift")
    if "Seed!ObserveUnknown" not in projection:
        raise RuntimeError("Revision Seed projection drift")
    return {
        "component_id": component_id,
        "operational_word": operational_word,
        "formal_operator": formal_operator,
        "pairing_proof": proof,
        "state": "proposals",
        "transition": "PROPOSE-REVISION",
        "validity": "target=genesis AND from-state!=to-state",
        "freshness": "proposal NOT-IN proposals",
        "effect": "append proposal",
        "seed_projection": "OBSERVE-UNKNOWN",
        "terminal_recognition_owned": False,
        "effect_permission_owned": False,
    }


