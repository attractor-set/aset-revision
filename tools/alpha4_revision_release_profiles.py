def build_release_profiles(root: Path, output: Path) -> dict[str, object]:
    if root.resolve() != ROOT.resolve():
        raise RuntimeError("release profile generator must run against repository root")
    if output.exists():
        shutil.rmtree(output)
    (output / "en").mkdir(parents=True)
    (output / "python").mkdir(parents=True)
    (output / "python-sqlite").mkdir(parents=True)

    record = companion_record()
    identity = source_digest((SUBJECT, FORTH, REL, CAUSAL, SEED_PROJECTION))
    english = output / "en/Revision.md"
    python_expression = output / "python/aset_revision_alpha4.py"
    sqlite_extension = output / "python-sqlite/aset_revision_alpha4_sqlite.py"
    sqlite_binding = output / "python-sqlite/PERSISTENCE_EXTENSION.json"
    write_english(english, record)
    write_python(python_expression, record, identity)
    write_python_sqlite(sqlite_extension, sha256(python_expression))
    write_python_sqlite_binding(sqlite_binding, python_expression, sqlite_extension)

    return {
        "record": record,
        "source_byte_identity_digest": identity,
        "english": english,
        "python": python_expression,
        "python_sqlite": sqlite_extension,
        "python_sqlite_binding": sqlite_binding,
    }
